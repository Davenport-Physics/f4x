//! Which CommonLibF4 the dump and the tables are made from (`--flavor`).
//!
//! | flavor | source | game build | out dir | table module |
//! |--------|--------|------------|---------|--------------|
//! | `og` (default) | `../CommonLibF4` (MIT) 67173f8d | 1.10.163 | `target/clangdump` | `og_1_10_163` |
//! | `ng` | `../commonlibf4-ng` = libxse/commonlibf4 (MIT) 40a93f69 | 1.11.x | `target/clangdump-ng` | `ng_1_11_240` |
//!
//! The next-gen headers include `REL/...` and `REX/...` from a GPL submodule that f4x
//! never uses; `shim-ng/` provides our own MIT replacements for the names they use.

use std::path::PathBuf;

use crate::workspace_root;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Flavor {
    Og,
    Ng,
}

const OG_TABLES_HEADER: &str = "\
// Generated by `cargo run -p f4x-codegen -- tables` from CommonLibF4 (MIT) commit
// 67173f8d44b9a928dbab983d25e576ac5f1e83ac via clang MS-ABI record and vtable layouts.
// Do not edit by hand. Provenance: provenance/codegen.jsonl (codegen/clf4-headers).
//
// Offsets are for Fallout 4 1.10.163 (old-gen). Every class module has SIZE, ALIGN,
// RTTI, one const per field offset, `bases::*` and (if polymorphic) `vtbl::*` slots.
#![allow(non_snake_case, non_upper_case_globals, non_camel_case_types, dead_code, clippy::all)]

";

const NG_TABLES_HEADER: &str = "\
// Generated by `cargo run -p f4x-codegen -- tables --flavor ng` from libxse/commonlibf4
// (MIT) commit 40a93f6917267f30d3551334ccd280402941c3c2 (the next-gen CommonLibF4 fork,
// last MIT commit) via clang MS-ABI record and vtable layouts, with f4x's own MIT shims
// for its REL/REX includes (crates/f4x-codegen/shim-ng). Do not edit by hand.
// Provenance: provenance/codegen.jsonl (codegen/clf4-ng-headers).
//
// Offsets are for Fallout 4 next-gen (headers target 1.11.221; f4x checks them against
// 1.11.240). Same module structure as og_1_10_163.rs: every class module has SIZE,
// ALIGN, RTTI, one const per field offset, `bases::*` and (if polymorphic) `vtbl::*`.
// The fork's top-level `Scaleform::` namespace is emitted as `RE::Scaleform::` (where
// the old-gen headers have it); OG names the fork renamed are aliased at the end of
// their module (crates/f4x-codegen/ng-aliases.txt).
#![allow(non_snake_case, non_upper_case_globals, non_camel_case_types, dead_code, clippy::all)]

";

impl Flavor {
    pub fn parse(text: &str) -> Result<Flavor, String> {
        match text {
            "og" => Ok(Flavor::Og),
            "ng" => Ok(Flavor::Ng),
            other => Err(format!("unknown flavor `{other}` (og or ng)")),
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Flavor::Og => "og",
            Flavor::Ng => "ng",
        }
    }

    /// The checkout used when `--clf4` is not given.
    pub fn default_clf4(self) -> PathBuf {
        workspace_root().join(match self {
            Flavor::Og => "../CommonLibF4",
            Flavor::Ng => "../commonlibf4-ng",
        })
    }

    pub fn default_out(self) -> PathBuf {
        workspace_root().join(match self {
            Flavor::Og => "target/clangdump",
            Flavor::Ng => "target/clangdump-ng",
        })
    }

    /// The commit `provenance/codegen.jsonl` cites.
    pub fn commit(self) -> &'static str {
        match self {
            Flavor::Og => "67173f8d44b9a928dbab983d25e576ac5f1e83ac",
            Flavor::Ng => "40a93f6917267f30d3551334ccd280402941c3c2",
        }
    }

    /// Headers included by the translation unit, relative to the include directory.
    pub fn umbrellas(self) -> &'static [&'static str] {
        match self {
            Flavor::Og => &["RE/Fallout.h", "F4SE/F4SE.h"],
            Flavor::Ng => &["RE/Fallout.h", "F4SE/F4SE.h", "Scaleform/Scaleform.h"],
        }
    }

    /// The header holding `enum class ENUM_FORM_ID`, relative to the checkout.
    pub fn form_types_header(self) -> &'static str {
        match self {
            Flavor::Og => "CommonLibF4/include/RE/Bethesda/TESForms.h",
            Flavor::Ng => "include/RE/E/ENUM_FORM_ID.h",
        }
    }

    /// `f4x-engine-sys/src/<module>.rs`.
    pub fn module(self) -> &'static str {
        match self {
            Flavor::Og => "og_1_10_163",
            Flavor::Ng => "ng_1_11_240",
        }
    }

    pub fn tables_header(self) -> &'static str {
        match self {
            Flavor::Og => OG_TABLES_HEADER,
            Flavor::Ng => NG_TABLES_HEADER,
        }
    }

    pub fn std(self) -> &'static str {
        match self {
            Flavor::Og => "-std=c++20",
            // The fork's xmake.lua: set_languages("c++23").
            Flavor::Ng => "-std=c++23",
        }
    }

    /// Our REL/REX shims (next-gen only).
    pub fn shim_dir(self) -> Option<PathBuf> {
        match self {
            Flavor::Og => None,
            Flavor::Ng => Some(workspace_root().join("crates/f4x-codegen/shim-ng")),
        }
    }

    /// Whether the headers need the pinned third-party headers (fmt, spdlog, mmio,
    /// Boost.STLInterfaces). The fork uses only the C++23 standard library.
    pub fn third_party(self) -> bool {
        self == Flavor::Og
    }

    /// Namespaces of the records the tables cover, each with the module path it is
    /// emitted under.
    pub fn table_namespaces(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Flavor::Og => &[("RE::", "RE::")],
            Flavor::Ng => &[("RE::", "RE::"), ("Scaleform::", "RE::Scaleform::")],
        }
    }

    /// RTTI class-key corrections read from the exe by `verify` (next-gen only).
    pub fn rtti_keys_file(self) -> Option<PathBuf> {
        match self {
            Flavor::Og => None,
            Flavor::Ng => Some(workspace_root().join("crates/f4x-codegen/ng-rtti-keys.txt")),
        }
    }

    /// Hand-written OG-name aliases for the tables (next-gen only).
    pub fn aliases_file(self) -> Option<PathBuf> {
        match self {
            Flavor::Og => None,
            Flavor::Ng => Some(workspace_root().join("crates/f4x-codegen/ng-aliases.txt")),
        }
    }
}
